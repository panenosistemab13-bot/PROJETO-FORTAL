export function getInitialVehicles(): VehicleItem[] {
  const dates = ['17/08/2026', '16/08/2026', '15/08/2026', '14/08/2026'];
  const times = ['06:15', '07:30', '08:45', '09:20', '10:10', '11:35', '13:00', '14:25', '15:50', '16:40', '17:15', '18:30'];
  const statuses: VehicleItem['status'][] = ['No Pátio', 'Em Trânsito', 'Carregando', 'No Pátio', 'No Pátio'];

  return INITIAL_VEHICLES_RAW.map((item, idx) => {
    let category: VehicleItem['category'] = 'Transportadora Parceira';
    if (item.carrier.startsWith('3C') && item.carrier.includes('DEDICADO')) {
      category = 'Dedicado 3C';
    } else if (item.carrier.startsWith('3C')) {
      category = 'Frota Própria 3C';
    }

    const date = dates[idx % dates.length];
    const time = times[idx % times.length];
    const status = statuses[idx % statuses.length];

    return {
      id: `v-${idx + 1}-${item.plate}`,
      plate: item.plate,
      fleet: item.fleet,
      carrier: item.carrier,
      category,
      dateAdded: date,
      timeAdded: time,
      status,
    };
  });
}
